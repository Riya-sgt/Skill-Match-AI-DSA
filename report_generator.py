from pathlib import Path
from xml.sax.saxutils import escape

class ReportGenerator:
    def generate_report(self, user, recommendations, filename="skill_report.txt"):
        report = [
            "========================================",
            "          SKILL MATCH AI REPORT",
            "========================================",
            f"Candidate Name : {user.name}",
            "",
            "Skills:"
        ]
        report.extend(f"- {skill}" for skill in user.skills)
        report.append("")
        report.append("Top Job Recommendations:")
        for item in recommendations:
            report.append(f"- {item['title']} -> {item['score']}%")
        report.extend([
            "",
            "========================================",
            "Report Generated By Skill Match AI",
            "========================================"
        ])

        Path(filename).write_text("\n".join(report), encoding="utf-8")
        print(f"\nReport saved as: {filename}")
        print("\n".join(report))
        return filename

    def export_pdf(self, user, recommendations, filename="skill_report.pdf"):
        try:
            from reportlab.lib.pagesizes import A4
            from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
            from reportlab.lib.styles import getSampleStyleSheet
        except ImportError:
            print("\nReportLab is not installed. Run: pip install reportlab")
            return None

        doc = SimpleDocTemplate(filename, pagesize=A4)
        styles = getSampleStyleSheet()
        story = [
            Paragraph("SKILL MATCH AI REPORT", styles["Title"]),
            Spacer(1, 12),
            Paragraph(f"Candidate Name: {escape(str(user.name))}", styles["BodyText"]),
            Spacer(1, 8),
            Paragraph("Skills:", styles["Heading2"]),
        ]
        for skill in user.skills:
            story.append(Paragraph(f"&#8226; {escape(str(skill))}", styles["BodyText"]))

        story.append(Spacer(1, 12))
        story.append(Paragraph("Top Job Recommendations", styles["Heading2"]))
        for item in recommendations:
            story.append(
                Paragraph(
                    f"{escape(str(item['title']))} - Match: {escape(str(item['score']))}%",
                    styles["BodyText"]
                )
            )

        doc.build(story)
        print(f"\nPDF Report exported: {filename}")
        return filename
